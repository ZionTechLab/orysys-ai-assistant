"""Research agent – Recursive Language Model (RLM) pattern.

Instead of putting whole documents into one prompt:

  research_planner     LLM writes a Python plan over the catalog (metadata only);
                       the sandbox runs it; errors are fed back so the LLM can repair
                       the plan (up to 3 attempts); deterministic search fallback.
        │  Send × N    one task per batch, run in parallel
        ▼
  research_worker      reads only targeted sections of its batch and extracts
                       structured findings (fast model). A batch that is too large
                       is split and sent to new workers – recursion, depth ≤ 2.
        │
        ▼
  research_aggregator  deferred: continues only when every selected document has a
                       finding (or a failure marker). Clusters causes into themes
                       (LLM), then counts them in code – the numbers are not
                       generated by the model.
        │
        ▼
  response_agent       writes the answer from themes + findings, with citations.
"""

import asyncio
import json
import re
import uuid
from datetime import date

from langchain_core.messages import AIMessage, HumanMessage, SystemMessage
from langgraph.runtime import Runtime
from langgraph.types import Command, Send

from app.graph.events import emit
from app.graph.nodes.common import node, parse_json
from app.graph.state import AgentState, UserContext
from app.llm import prompts
from app.llm.factory import get_llm
from app.rlm.catalog import Catalog, CatalogError
from app.rlm.sandbox import run_plan
from app.security.guards import sanitize_retrieved

MAX_DOCS = 24
PLAN_ATTEMPTS = 3
WORKER_MAX_DOCS = 3      # a worker analyses at most this many documents itself …
MAX_DEPTH = 2            # … larger batches are split recursively, up to this depth
SECTIONS_PER_DOC = 3
PREFERRED_SECTIONS = ("summary", "root-cause", "impact", "resolution", "actions")
SOURCE_CHARS = 700       # text kept per section for the final answer's evidence


# ---------- planner ----------

def _question(state: AgentState) -> str:
    return state["messages"][-1].content


def _extract_code(text: str) -> str:
    match = re.search(r"```(?:python)?\s*\n(.*?)```", text, flags=re.DOTALL)
    return (match.group(1) if match else text).strip()


def validate_batches(result, catalog: Catalog) -> list[list[str]]:
    """Check the plan's output: batches of visible document ids, no duplicates, bounded."""
    if not isinstance(result, dict) or not isinstance(result.get("batches"), list):
        raise ValueError('result must be {"batches": [[doc_id, ...], ...]}')
    seen: set[str] = set()
    batches: list[list[str]] = []
    for batch in result["batches"]:
        if not isinstance(batch, list):
            raise ValueError("each batch must be a list of doc ids")
        clean = []
        for doc_id in batch:
            doc_id = str(doc_id)
            if doc_id in seen:
                continue
            catalog.get_doc(doc_id)  # raises CatalogError if unknown or not visible
            seen.add(doc_id)
            clean.append(doc_id)
        if clean:
            batches.append(clean)
    if not seen:
        raise ValueError("the plan selected no documents; widen the filters or use search()")
    if len(seen) > MAX_DOCS:
        raise ValueError(f"the plan selected {len(seen)} documents; the maximum is {MAX_DOCS} – filter more")
    return batches


async def _fallback_batches(question: str, catalog: Catalog) -> list[list[str]]:
    """If no valid plan after all attempts: take the documents of the top search hits."""
    hits = await catalog.search(question, top_k=10)
    ids = list(dict.fromkeys(h["doc_id"] for h in hits))
    return [ids[i:i + 3] for i in range(0, len(ids), 3)]


def _planner_failed(state: AgentState, _exc: Exception) -> dict:
    return {"research": {"turn_id": uuid.uuid4().hex, "question": _question(state), "doc_ids": [], "batches": []},
            "degraded": {"research_unavailable": True}}


@node("research_planner", on_error=_planner_failed)
async def research_planner(state: AgentState, runtime: Runtime[UserContext]) -> dict:
    question = _question(state)
    catalog = Catalog(runtime.context.clearance)
    system = (prompts.RESEARCH_PLANNER
              .replace("{today}", date.today().isoformat())
              .replace("{overview}", json.dumps(catalog.describe())))
    messages = [SystemMessage(system), HumanMessage(f"Question: {question}")]
    llm = get_llm("strong", long=True)

    batches, code, attempts, used_fallback = [], "", 0, False
    for attempts in range(1, PLAN_ATTEMPTS + 1):
        try:
            reply = await llm.ainvoke(messages)
        except Exception as exc:  # noqa: BLE001 – LLM down/slow: select documents by search instead
            emit("rlm_plan", attempt=attempts, ok=False, code="", error=f"LLM unavailable ({type(exc).__name__})",
                 documents=0, batches=0, lines_executed=0, catalog_calls={})
            break
        code = _extract_code(reply.content)
        run = await run_plan(code, catalog)
        error = run.error
        if run.ok:
            try:
                batches = validate_batches(run.result, catalog)
            except (ValueError, CatalogError) as exc:
                error = str(exc)
        emit("rlm_plan", attempt=attempts, ok=error is None, code=code, error=error,
             documents=sum(len(b) for b in batches), batches=len(batches),
             lines_executed=run.lines_executed, catalog_calls=run.catalog_usage)
        if error is None:
            break
        # Repair loop: the model sees its own plan and the sandbox's error message.
        messages += [AIMessage(reply.content), HumanMessage(prompts.RESEARCH_PLAN_REPAIR.format(error=error))]
        batches = []

    if not batches:
        batches, used_fallback = await _fallback_batches(question, catalog), True
        emit("rlm_fallback", reason="no valid plan – documents selected by search",
             documents=sum(len(b) for b in batches))

    doc_ids = [d for b in batches for d in b]
    emit("rlm_batches", batches=batches, documents=len(doc_ids))
    return {"research": {"turn_id": uuid.uuid4().hex, "question": question, "plan_code": code,
                         "plan_attempts": attempts, "used_fallback": used_fallback,
                         "doc_ids": doc_ids, "batches": batches}}


def fan_out(state: AgentState):
    """One parallel worker per batch (LangGraph Send). Nothing to analyse -> straight to the answer."""
    research = state.get("research") or {}
    if not research.get("batches"):
        return "response_agent"
    return [Send("research_worker", {"turn_id": research["turn_id"], "question": research["question"],
                                     "batch": batch, "batch_no": str(i), "depth": 0})
            for i, batch in enumerate(research["batches"], start=1)]


# ---------- worker ----------

def _choose_sections(sections: list[str]) -> list[str]:
    """Targeted reading: the sections that usually answer analysis questions, else the first few."""
    by_slug = {re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-"): s for s in sections}
    chosen = [by_slug[s] for s in PREFERRED_SECTIONS if s in by_slug]
    return (chosen or sections)[:SECTIONS_PER_DOC]


def _worker_failed(task: dict, exc: Exception) -> dict:
    return {"findings": [{"turn_id": task["turn_id"], "doc_id": d, "batch_no": task["batch_no"],
                         "error": f"analysis failed ({type(exc).__name__})"} for d in task["batch"]]}


@node("research_worker", on_error=_worker_failed)
async def research_worker(task: dict, runtime: Runtime[UserContext]):
    batch, depth, batch_no = task["batch"], task["depth"], task["batch_no"]

    # Recursion: a batch too large for one worker is split and handed to new workers.
    if len(batch) > WORKER_MAX_DOCS and depth < MAX_DEPTH:
        half = (len(batch) + 1) // 2
        parts = [batch[:half], batch[half:]]
        emit("rlm_recurse", batch_no=batch_no, depth=depth, split=[len(p) for p in parts])
        return Command(goto=[Send("research_worker", {**task, "batch": p, "batch_no": f"{batch_no}.{i}",
                                                      "depth": depth + 1})
                             for i, p in enumerate(parts, start=1)])

    catalog = Catalog(runtime.context.clearance)
    # Documents of the batch are analysed in parallel – one small, focused LLM call each.
    findings = await asyncio.gather(*(_analyse_document(doc_id, task, catalog) for doc_id in batch))

    emit("rlm_worker", batch_no=batch_no, depth=depth, documents=batch,
         sections_read=catalog.usage["read_section"], chars_read=catalog.usage["chars_read"],
         findings=sum(1 for f in findings if not f.get("error") and f.get("relevant")),
         not_relevant=[f["doc_id"] for f in findings if not f.get("error") and not f.get("relevant")],
         failed=[f["doc_id"] for f in findings if f.get("error")])
    return {"findings": list(findings)}


def _section_id(doc_id: str, section: str) -> str:
    return f"{doc_id}#{re.sub(r'[^a-z0-9]+', '-', section.lower()).strip('-')}"


async def _analyse_document(doc_id: str, task: dict, catalog: Catalog) -> dict:
    """Read the targeted sections of one document and extract a structured finding.

    Never raises: a failure becomes a finding with `error`, so the aggregator still knows
    the document was attempted (completeness) and the answer can say what was missed.
    """
    base = {"turn_id": task["turn_id"], "doc_id": doc_id, "batch_no": task["batch_no"]}
    try:
        meta = catalog.get_doc(doc_id)
        read = []
        for section in _choose_sections(meta["sections"]):
            checked = sanitize_retrieved(catalog.read_section(doc_id, section))
            if checked.flags:
                emit("content_flagged", chunk_id=_section_id(doc_id, section), flags=checked.flags)
            text = checked.text
            read.append({"chunk_id": _section_id(doc_id, section), "title": meta["title"], "section": section,
                         "date": meta["created_date"], "text": text})
        # Metadata (department, type, severity) is not in the section text – give it to the analyst too.
        attrs = (f'department="{meta["department"]}" type="{meta["document_type"]}" '
                 f'severity="{meta.get("severity") or "n/a"}"')
        blocks = "\n\n".join(f'<document id="{s["chunk_id"]}" title="{s["title"]}" date="{s["date"]}" {attrs}>\n'
                             f'{s["text"]}\n</document>' for s in read)
        reply = await get_llm("fast", long=True).ainvoke([
            SystemMessage(prompts.RESEARCH_WORKER.format(question=task["question"])),
            HumanMessage(blocks),
        ])
        f = parse_json(reply.content)
    except CatalogError as exc:
        return {**base, "error": str(exc)}
    except Exception as exc:  # noqa: BLE001 – LLM failure or unparseable output for this one document
        return {**base, "error": f"analysis failed ({type(exc).__name__})"}

    read_ids = [s["chunk_id"] for s in read]
    # Accept "INC-1#root-cause" and also bare section slugs; never accept ids that were not read.
    cited = [c for c in f.get("citations", []) if isinstance(c, str) and c in read_ids] or read_ids
    relevant = f.get("relevant", True) not in (False, "false", "False", 0)
    return {
        **base, "relevant": relevant, "title": meta["title"],
        "date": str(f.get("date") or meta["created_date"])[:10],
        "summary": str(f.get("summary", ""))[:400], "cause_category": str(f.get("cause_category", ""))[:80],
        "cause": str(f.get("cause", ""))[:400], "impact": str(f.get("impact", ""))[:300],
        "citations": cited,
        "sources": [{**s, "text": s["text"][:SOURCE_CHARS]} for s in read if s["chunk_id"] in cited],
    }


# ---------- aggregator ----------

def group_by_category(findings: list[dict]) -> list[dict]:
    """Deterministic fallback grouping by the workers' cause labels."""
    groups: dict[str, list[str]] = {}
    for f in findings:
        label = (f.get("cause_category") or "other").strip().lower()
        groups.setdefault(label, []).append(f["doc_id"])
    return [{"theme": k, "doc_ids": v, "explanation": ""} for k, v in groups.items()]


def finalize_themes(raw: list[dict], findings: list[dict]) -> list[dict]:
    """Keep only real doc ids, one theme per document, unassigned documents kept; count in code."""
    valid = {f["doc_id"] for f in findings}
    assigned: set[str] = set()
    themes = []
    for t in raw:
        if not isinstance(t, dict):
            continue
        ids = [d for d in dict.fromkeys(map(str, t.get("doc_ids", []))) if d in valid and d not in assigned]
        if ids:
            assigned |= set(ids)
            themes.append({"theme": str(t.get("theme", "")).strip()[:80] or "other", "doc_ids": ids,
                           "explanation": str(t.get("explanation", ""))[:300]})
    leftovers = [f for f in findings if f["doc_id"] not in assigned]
    themes += group_by_category(leftovers)
    for t in themes:
        t["count"] = len(t["doc_ids"])
    return sorted(themes, key=lambda t: (-t["count"], t["theme"]))


async def _cluster(findings: list[dict], question: str) -> tuple[list[dict], bool]:
    lines = "\n".join(f'{f["doc_id"]} | {f["date"]} | {f["cause_category"]} | {f["cause"]}' for f in findings)
    try:
        reply = await get_llm("strong", long=True).ainvoke([
            SystemMessage(prompts.RESEARCH_AGGREGATOR.format(question=question)),
            HumanMessage(f"Findings (doc_id | date | cause label | cause):\n{lines}"),
        ])
        return finalize_themes(parse_json(reply.content).get("themes", []), findings), True
    except Exception:  # noqa: BLE001 – clustering is optional; fall back to the workers' own labels
        return finalize_themes(group_by_category(findings), findings), False


def _evidence(findings: list[dict]) -> list[dict]:
    seen, evidence = set(), []
    for f in findings:
        for s in f.get("sources", []):
            if s["chunk_id"] not in seen:
                seen.add(s["chunk_id"])
                evidence.append({"chunk_id": s["chunk_id"], "doc_id": f["doc_id"], "title": s["title"],
                                 "section": s["section"], "text": s["text"], "score": 1.0,
                                 "document_type": "", "created_date": s["date"]})
    return evidence


def _aggregator_failed(state: AgentState, _exc: Exception) -> Command:
    turn = (state.get("research") or {}).get("turn_id")
    ok = [f for f in state.get("findings", []) if f.get("turn_id") == turn and not f.get("error")
          and f.get("relevant")]
    return Command(goto="response_agent", update={"evidence": _evidence(ok)})


@node("research_aggregator", on_error=_aggregator_failed)
async def research_aggregator(state: AgentState, runtime: Runtime[UserContext]) -> Command:
    research = state.get("research") or {}
    turn = research.get("turn_id")
    findings = [f for f in state.get("findings", []) if f.get("turn_id") == turn]
    expected = set(research.get("doc_ids", []))
    covered = {f["doc_id"] for f in findings}

    # Recursive workers may still be running: continue only when every document is covered.
    if not expected <= covered:
        emit("rlm_waiting", covered=len(covered & expected), expected=len(expected))
        return Command(goto=[])

    ok = [f for f in findings if not f.get("error") and f.get("relevant")]
    themes, clustered_by_llm = await _cluster(ok, research.get("question", "")) if ok else ([], False)
    emit("rlm_aggregate", documents=len(expected), analysed=len(ok),
         not_relevant=sorted(f["doc_id"] for f in findings if not f.get("error") and not f.get("relevant")),
         failed=sorted(f["doc_id"] for f in findings if f.get("error")), clustered_by_llm=clustered_by_llm,
         themes=[{"theme": t["theme"], "count": t["count"], "doc_ids": t["doc_ids"]} for t in themes])
    return Command(goto="response_agent", update={"research": {**research, "themes": themes},
                                                  "evidence": _evidence(ok)})


def research_block(state: AgentState) -> str:
    """Text given to the response agent: themes with counts (computed in code) and per-document findings."""
    research = state.get("research") or {}
    turn = research.get("turn_id")
    findings = [f for f in state.get("findings", []) if f.get("turn_id") == turn]
    if not research.get("doc_ids"):
        return "The research could not be carried out (no documents could be selected or the service failed)."
    lines = [f"Documents analysed: {len(research['doc_ids'])} ({', '.join(research['doc_ids'])})"]
    lines.append("Themes (count computed from the findings):")
    for t in research.get("themes", []):
        lines.append(f"- {t['theme']}: {t['count']} – {', '.join(t['doc_ids'])}. {t.get('explanation', '')}")
    lines.append("Findings per document:")
    for f in sorted(findings, key=lambda f: f.get("date", "")):
        if f.get("error"):
            lines.append(f"- {f['doc_id']}: NOT ANALYSED ({f['error']})")
        elif not f.get("relevant"):
            lines.append(f"- {f['doc_id']}: excluded – not relevant to the question ({f.get('summary', '')})")
        else:
            lines.append(f"- {f['doc_id']} ({f['date']}): {f['summary']} Cause: {f['cause']} "
                         f"Impact: {f['impact']} Sources: {', '.join(f['citations'])}")
    return "\n".join(lines)
